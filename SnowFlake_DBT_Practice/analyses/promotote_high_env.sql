--Row Access Policy
CREATE OR REPLACE ROW ACCESS POLICY region_policy
AS (region VARCHAR) RETURNS BOOLEAN ->
    CASE
        WHEN IS_ROLE_IN_SESSION('GLOBAL_ADMIN')
        THEN TRUE
        WHEN IS_ROLE_IN_SESSION('INDIA_ANALYST')
             AND region = 'INDIA'
        THEN TRUE
        WHEN IS_ROLE_IN_SESSION('US_ANALYST')
             AND region = 'US'
        THEN TRUE
        ELSE FALSE
    END;

ALTER TABLE claims
ADD ROW ACCESS POLICY region_policy
ON (region);


