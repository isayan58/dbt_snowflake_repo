--Masking Policy
CREATE OR REPLACE MASKING POLICY Host_mask
AS (val VARCHAR) RETURNS VARCHAR ->
    CASE
        WHEN IS_ROLE_IN_SESSION('ACCOUNTADMIN')
        THEN val
        ELSE '****'
    END;

